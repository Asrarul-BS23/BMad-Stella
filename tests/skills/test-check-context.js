'use strict';

// stella-project-context/scripts/check-context.js — the deterministic check the skill
// runs after writing. A good context.md passes; a missing file, a bad provenance line,
// over 60 lines, a line that states a rule, and a missing path each fail with a named
// reason. Rule words inside backticks are ignored. Path extraction ignores commands,
// placeholders, URLs and generics; globs are checked by their fixed prefix. The CLI
// prints `ok` / `FAIL:` lines with exit codes 0 / 1 / 10.

const fs = require('node:fs');
const os = require('node:os');
const path = require('node:path');
const { spawnSync } = require('node:child_process');

const REPO = path.resolve(__dirname, '..', '..');
const SCRIPT = path.join(
  REPO,
  'stella',
  'skills',
  'stella-project-context',
  'scripts',
  'check-context.js',
);
const check = require(SCRIPT);
const CTX = ['_bmad-output', 'stella', 'project-context'];
const LABEL = '_bmad-output/stella/project-context/context.md';

let fails = 0;
let total = 0;
const ok = (c, m) => {
  total++;
  if (!c) {
    fails++;
    console.log('FAIL ' + m);
  }
};

const PROV = (sha = 'abc1234') =>
  `<!-- Verified 2026-10-27 against ${sha}. Managed by stella-project-context; refresh re-verifies every line. -->`;

const GOOD = [
  PROV(),
  '',
  '# demo',
  '',
  '## Where things are',
  '',
  '- Entry point `src/app.js`; docs in `docs/`; the mapper is `Order.cs`.',
  '- `src/generated/**` is generated by `pnpm codegen`.',
  '- `legacy/` is excluded from the build; its live replacement is `src/`.',
  '- Handlers implement `IRequest<T>`; placeholders like `{spec_file}` are not paths.',
  '- Wiki: `https://example.test/wiki`.',
  '',
  '## Layers',
  '',
  '| Layer | Path | May reference |',
  '| --- | --- | --- |',
  '| App | `src/` | nothing |',
  '',
  '## Copy the shape from',
  '',
  '- Route: `src/app.js`',
];

function makeRoot(content = GOOD.join('\n') + '\n') {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'ctx-check-'));
  fs.mkdirSync(path.join(root, ...CTX), { recursive: true });
  fs.mkdirSync(path.join(root, 'src', 'generated'), { recursive: true });
  fs.mkdirSync(path.join(root, 'docs'));
  fs.mkdirSync(path.join(root, 'legacy'));
  fs.writeFileSync(path.join(root, 'src', 'app.js'), '');
  fs.writeFileSync(path.join(root, 'Order.cs'), '');
  if (content !== null) fs.writeFileSync(path.join(root, ...CTX, 'context.md'), content);
  return root;
}
const failuresOf = (root) => check.checkContext(root).failures;
const withLines = (extra) => makeRoot([...GOOD, ...extra].join('\n') + '\n');

// ---- constants ----
ok(check.CONTEXT_LABEL === LABEL, 'constants: one file, context.md');
ok(check.BUDGET === 60, 'constants: budget 60');

// ---- good file passes ----
{
  const r = check.checkContext(makeRoot());
  ok(r.ok, `good: passes (${r.failures.join(' | ')})`);
  const none = makeRoot(GOOD.map((l, i) => (i === 0 ? PROV('none') : l)).join('\n'));
  ok(check.checkContext(none).ok, 'good: provenance sha `none` accepted');
}

// ---- missing file ----
ok(failuresOf(makeRoot(null)).includes(`${LABEL} missing`), 'missing: reported');

// ---- provenance ----
{
  const old = GOOD.map((l, i) =>
    i === 0
      ? '<!-- Verified 2026-10-27 against abc1234. Managed by stella-project-context; edits are replaced on refresh. -->'
      : l,
  );
  ok(
    failuresOf(makeRoot(old.join('\n'))).includes(`${LABEL} line 1 is not the provenance line`),
    'provenance: old wording fails',
  );
}

// ---- budget ----
{
  const lines = [...GOOD];
  while (lines.length < 60) lines.push('- filler');
  ok(check.checkContext(makeRoot(lines.join('\n') + '\n')).ok, 'budget: 60 lines passes');
  lines.push('- one more');
  ok(
    failuresOf(makeRoot(lines.join('\n') + '\n')).includes(`${LABEL} has 61 lines, budget 60`),
    'budget: 61 lines fails',
  );
}

// ---- rule words ----
{
  for (const word of ['Never', 'always', 'must', 'should', "don't", 'Do not', "shouldn't"]) {
    const f = failuresOf(withLines([`- ${word} edit \`src/app.js\` by hand.`]));
    ok(
      f.some((x) => /line \d+ states a rule; write the fact instead/.test(x)),
      `rule: "${word}" fails`,
    );
  }
  ok(
    check.checkContext(withLines(['- The flag is `--always-run`.'])).ok,
    'rule: words inside backticks are ignored',
  );
  ok(
    check.checkContext(withLines(['- The mustard service lives in `src/`.'])).ok,
    'rule: whole words only',
  );
  ok(
    check.ruleLines(`${PROV()}\n- fact\n- Always rebuild.\n`).join(',') === '3',
    'rule: line numbers are 1-based and skip the provenance line',
  );
}

// ---- missing path ----
{
  const f = failuresOf(withLines(['- See `src/missing.js`.']));
  ok(
    f.includes(`${LABEL} cites a path that does not exist: src/missing.js`),
    'path: missing reported',
  );
}

// ---- path extraction ----
{
  const text = [
    '`src/app.js` `docs/` `./src/app.js` `.env*` `src/generated/**` `Order.cs`',
    '`pnpm codegen` `{spec_file}` `https://example.test/x` `IRequest<T>` `--flag` `BeginTransactionAsync`',
    '`docs/lessons.md §2` `@project-context/project.md` `a=b/c` `src/x|y`',
  ].join('\n');
  const got = check.pathCandidates(text).sort();
  const want = ['.env', 'Order.cs', 'docs', 'src/app.js', 'src/generated'].sort();
  ok(got.join(',') === want.join(','), `extract: ${got.join(',')} === ${want.join(',')}`);
}

// ---- main(): exit codes and output ----
{
  const lines = [];
  ok(
    check.main([makeRoot()], { log: (s) => lines.push(s) }) === 0 && lines.join('') === 'ok',
    'main: good root → 0 and `ok`',
  );
  const bad = [];
  ok(
    check.main([makeRoot(null)], { log: (s) => bad.push(s) }) === 1 &&
      bad.every((l) => l.startsWith('FAIL: ')),
    'main: failures → 1 and FAIL lines',
  );
  ok(
    check.main([path.join(os.tmpdir(), 'does-not-exist-' + Date.now())], { log: () => {} }) === 10,
    'main: bad root → 10',
  );
}

// ---- CLI ----
{
  const good = makeRoot();
  const r = spawnSync(process.execPath, [SCRIPT, good], { encoding: 'utf8' });
  ok(r.status === 0 && r.stdout.trim() === 'ok', `cli: ok on good root (${r.stdout.trim()})`);
  const cwd = spawnSync(process.execPath, [SCRIPT], { encoding: 'utf8', cwd: good });
  ok(cwd.status === 0 && cwd.stdout.trim() === 'ok', 'cli: defaults to cwd');
  const bad = spawnSync(process.execPath, [SCRIPT, makeRoot(null)], { encoding: 'utf8' });
  ok(
    bad.status === 1 && /^FAIL: .*context\.md missing/m.test(bad.stdout),
    'cli: exit 1 with FAIL line',
  );
}

console.log(`check-context: ${total - fails}/${total} passed${fails ? ` — ${fails} FAILED` : ''}`);
process.exit(fails ? 1 : 0);
